import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const projectRoot = new URL("../", import.meta.url);
const manifestUrl = new URL("runtime/knowledge-agent/manifest.json", projectRoot);
const outputUrl = new URL("lib/agent/fixed-runtime.generated.ts", projectRoot);
const manifest = JSON.parse(await readFile(manifestUrl, "utf8"));

const entries = [
  ["FIXED_QUERY_SKILL", "skills/kb-query/SKILL.md"],
  ["FIXED_INGEST_SKILL", "skills/kb-ingest/SKILL.md"],
  ["FIXED_OKF_SCRIPT", "scripts/okf.py"],
];

const constants = [];
for (const [constant, relativePath] of entries) {
  const content = await readFile(new URL(`runtime/knowledge-agent/${relativePath}`, projectRoot), "utf8");
  const actual = createHash("sha256").update(content).digest("hex");
  const expected = manifest.files[relativePath];
  if (actual !== expected) {
    throw new Error(`Fixed runtime hash mismatch for ${relativePath}: expected ${expected}, got ${actual}`);
  }
  constants.push(`export const ${constant} = ${JSON.stringify(content)};`);
}

const generated = [
  "// Generated by scripts/generate-fixed-runtime.mjs. Do not edit manually.",
  `export const FIXED_RUNTIME_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const;`,
  ...constants,
].join("\n\n") + "\n";

let existing = "";
try {
  existing = await readFile(outputUrl, "utf8");
} catch {
  // The first generation creates the file.
}
if (existing !== generated) await writeFile(outputUrl, generated, "utf8");

console.log(`Verified ${manifest.runtimeVersion} and generated ${fileURLToPath(outputUrl)}`);
